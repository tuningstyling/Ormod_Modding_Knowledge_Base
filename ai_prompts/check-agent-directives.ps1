<#
.SYNOPSIS
  Verifies that every AI-tool adapter in this repository points at AGENTS.md, the top directive.

.DESCRIPTION
  AGENTS.md is the only file you edit. Checks:
    - CLAUDE.md contains the line  @AGENTS.md           (Claude Code imports AGENTS.md)
    - .gemini\settings.json lists AGENTS.md in context.fileName   (Gemini CLI reads AGENTS.md)
    - .aiassistant\rules\ormod-directive.md is an exact generated copy of AGENTS.md   (JetBrains AI Assistant has no import)
  Line endings are ignored, so Windows autocrlf does not cause false alarms.

.PARAMETER Fix
  Regenerates the generated copy from AGENTS.md. CLAUDE.md and the Gemini settings are never rewritten; they are only reported.
#>
[CmdletBinding()]
param(
    [switch]$Fix,
    [string]$Root = (Split-Path -Parent $PSScriptRoot)
)

$ErrorActionPreference = 'Stop'

function Read-Lf([string]$Path) { return ((Get-Content -LiteralPath $Path -Raw) -replace "`r`n", "`n") }

$Agents = Join-Path $Root 'AGENTS.md'
if (-not (Test-Path -LiteralPath $Agents)) { throw "AGENTS.md not found in $Root" }

$Header   = "<!-- GENERATED from AGENTS.md by scripts/check-agent-directives.ps1 -Fix. Do not edit this file; edit AGENTS.md. -->`n`n"
$Expected = $Header + (Read-Lf $Agents)
$Problems = New-Object System.Collections.Generic.List[string]

$Claude = Join-Path $Root 'CLAUDE.md'
if (-not (Test-Path -LiteralPath $Claude)) { $Problems.Add('CLAUDE.md is missing') }
elseif (-not (((Read-Lf $Claude) -split "`n") | Where-Object { $_.Trim() -eq '@AGENTS.md' })) { $Problems.Add('CLAUDE.md does not contain the line @AGENTS.md') }

$Gemini = Join-Path (Join-Path $Root '.gemini') 'settings.json'
if (-not (Test-Path -LiteralPath $Gemini)) { $Problems.Add('.gemini/settings.json is missing') }
else {
    $Settings = Get-Content -LiteralPath $Gemini -Raw | ConvertFrom-Json
    if (@($Settings.context.fileName) -notcontains 'AGENTS.md') { $Problems.Add('.gemini/settings.json: context.fileName does not include AGENTS.md') }
}

$Utf8NoBom = New-Object System.Text.UTF8Encoding($false)
foreach ($Relative in @('.aiassistant/rules/ormod-directive.md')) {
    $Path = Join-Path $Root $Relative
    if ($Fix) {
        New-Item -ItemType Directory -Path (Split-Path -Parent $Path) -Force | Out-Null
        [System.IO.File]::WriteAllText($Path, $Expected, $Utf8NoBom)
        Write-Host "Regenerated $Relative"
    }
    elseif (-not (Test-Path -LiteralPath $Path)) { $Problems.Add("$Relative is missing (run with -Fix)") }
    elseif ((Read-Lf $Path) -ne $Expected) { $Problems.Add("$Relative differs from AGENTS.md (run with -Fix)") }
}

if ($Problems.Count -gt 0) {
    foreach ($p in $Problems) { Write-Host "PROBLEM  $p" -ForegroundColor Red }
    exit 1
}
Write-Host 'OK: all agent adapters match AGENTS.md.' -ForegroundColor Green
